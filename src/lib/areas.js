// Ελληνικά -> λατινικά, ΦΩΝΗΤΙΚΑ (όχι μεταγραφή γραμμάτων)
const GREEK_MAP = {
  α: 'a', β: 'v', γ: 'g', δ: 'd', ε: 'e', ζ: 'z', η: 'i', θ: 'th',
  ι: 'i', κ: 'k', λ: 'l', μ: 'm', ν: 'n', ξ: 'x', ο: 'o', π: 'p',
  ρ: 'r', σ: 's', ς: 's', τ: 't', υ: 'i', φ: 'f', χ: 'h', ψ: 'ps',
  ω: 'o',
};

/**
 * Φωνητική κανονικοποίηση.
 * «Κολωνάκι», «κολονακι», «Kolonaki» -> όλα "kolonaki"
 */
export function phonetic(input) {
  if (!input) return '';

  let s = String(input)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')  // τόνοι και διαλυτικά
    .toLowerCase()
    .trim();

  // Ελληνικοί δίφθογγοι ΠΡΙΝ από τα μονά γράμματα
  s = s
    .replace(/ου/g, 'u')
    .replace(/αι/g, 'e')
    .replace(/ει|οι|υι/g, 'i')
    .replace(/αυ/g, 'af')
    .replace(/ευ/g, 'ef')
    .replace(/μπ/g, 'b')
    .replace(/ντ/g, 'd')
    .replace(/γκ|γγ/g, 'g')
    .replace(/τσ/g, 'ts')
    .replace(/τζ/g, 'tz');

  // Μονά ελληνικά γράμματα
  s = s.split('').map(ch => GREEK_MAP[ch] ?? ch).join('');

  // Λατινικοί συνδυασμοί που αποδίδουν τους ίδιους ήχους
  s = s
    .replace(/ch|kh/g, 'h')
    .replace(/ph/g, 'f')
    .replace(/ps/g, 'ps')
    .replace(/oo/g, 'u')
    .replace(/ee/g, 'i')
    .replace(/ai/g, 'e')
    .replace(/ou/g, 'u')
    .replace(/y/g, 'i')
    .replace(/w/g, 'o')
    .replace(/q/g, 'k')
    .replace(/c/g, 'k');

  // Διπλά σύμφωνα: «Βριλήσσια» = «Βριλήσια»
  s = s.replace(/(.)\1+/g, '$1');

  // Ό,τι δεν είναι γράμμα ή ψηφίο φεύγει — κενά, παύλες, τελείες
  return s.replace(/[^a-z0-9]/g, '');
}

/**
 * Ταιριάζουν δύο περιοχές; Ανεκτικό σε ορθογραφία και greeklish.
 */
export function areasMatch(a, b) {
  const pa = phonetic(a);
  const pb = phonetic(b);
  if (!pa || !pb) return false;
  if (pa === pb) return true;
  // Το ένα περιέχει το άλλο: «Νέα Σμύρνη» vs «Σμύρνη»
  if (pa.length >= 4 && pb.length >= 4) {
    return pa.includes(pb) || pb.includes(pa);
  }
  return false;
}

/**
 * Προτάσεις για autocomplete. Πρώτα όσες ξεκινούν με τον όρο.
 */
export function searchAreas(query, limit = 8, exclude = []) {
  const q = phonetic(query);
  if (!q) return [];

  const excluded = new Set(exclude.map(phonetic));

  const scored = ATHENS_AREAS
    .filter(a => !excluded.has(phonetic(a)))
    .map(area => {
      const p = phonetic(area);
      let score = 0;
      if (p === q) score = 100;
      else if (p.startsWith(q)) score = 80;
      else if (p.includes(q)) score = 60;
      // Ταίριασμα σε δεύτερη λέξη: «σμυρνη» -> «Νέα Σμύρνη»
      else if (area.split(/\s+/).some(w => phonetic(w).startsWith(q))) score = 50;
      return { area, score };
    })
    .filter(x => x.score > 0)
    .sort((a, b) => b.score - a.score || a.area.localeCompare(b.area, 'el'))
    .slice(0, limit);

  return scored.map(x => x.area);
}

/**
 * Βρίσκει την επίσημη γραφή. «kolonaki» -> «Κολωνάκι»
 * Επιστρέφει null αν δεν υπάρχει στη λίστα.
 */
export function canonicalArea(input) {
  const p = phonetic(input);
  if (!p) return null;
  return ATHENS_AREAS.find(a => phonetic(a) === p) || null;
}